// ============================================================
// mic_uploader.h
// ESP32 → PC 录音分块上传
// ============================================================
//
// 协议：
//
//   RECM | u16 flags | u32 chunk_size | PCM
//   RPTF | u32 total_size
//
// 语音状态：
//
//   IDLE
//      ↓
//   RECORDING
//      ↓
//   RPTF
//      ↓
//   WAITING_FOR_PLAYBACK
//      ↓
//   PLAYBACK
//      ↓
//   COOLDOWN
//      ↓
//   IDLE
//
// 重要：
//
//   播放期间不执行 VAD。
//   播放期间产生的麦克风 PCM 会被丢弃。
//   播放结束后再等待一段时间，
//   然后清空 Ring Buffer，重新开始监听。
//
// ============================================================

#ifndef MIC_UPLOADER_H
#define MIC_UPLOADER_H

#include "network/wifi_client.h"
#include "audio/mic_adc.h"
#include "vad/energy_vad.h"


// ============================================================
// REC chunk
// ============================================================

#define REC_CHUNK_BYTES       4096

// 目标：约每 100 ms 发送一次
#define REC_CHUNK_INTERVAL_MS 100


// ============================================================
// 播放结束后的声学冷却时间
//
// 作用：
//
//   1. 等待喇叭余音消失
//   2. 等待房间反射声消失
//   3. 防止播放最后几个音节再次触发 VAD
//
// 500 ms 是第一版比较保守的值。
// 如果以后测试很好，可以降到 300 ms。
// ============================================================

#define MIC_PLAYBACK_COOLDOWN_MS 500


class MicUploader {

public:

    // --------------------------------------------------------
    // 构造函数
    // --------------------------------------------------------

    MicUploader();

    // --------------------------------------------------------
    // 初始化
    // --------------------------------------------------------

    void begin(
        WifiClient *wifi,
        MicAdc *mic,
        EnergyVad *vad
    );

    // --------------------------------------------------------
    // 主循环调用
    // --------------------------------------------------------

    void run();

    // --------------------------------------------------------
    // 播放期间是否正在等待播放
    //
    // true：
    //   当前不能开始下一轮录音。
    // --------------------------------------------------------

    bool waitingForPlayback() const;

    // --------------------------------------------------------
    // PLAY 完成后调用
    //
    // 不立即恢复 VAD。
    // 先进入 cooldown。
    // --------------------------------------------------------

    void notifyPlaybackDone();

    // --------------------------------------------------------
    // 当前 session 累计 PCM 字节
    // --------------------------------------------------------

    uint32_t sessionBytes() const
    {
        return _sessionBytes;
    }


private:

    // --------------------------------------------------------
    // 发送 REC chunk
    // --------------------------------------------------------

    bool sendRecChunk(
        const int16_t *samples,
        size_t n,
        uint16_t flags
    );

    // --------------------------------------------------------
    // 发送 RPTF
    // --------------------------------------------------------

    void sendReport(uint32_t totalBytes);

    // --------------------------------------------------------
    // 清空当前麦克风数据
    //
    // 主要用于播放期间和 cooldown。
    // --------------------------------------------------------

    void discardMicSamples();


private:

    WifiClient *_wifi;
    MicAdc     *_mic;
    EnergyVad  *_vad;

    // --------------------------------------------------------
    // 当前录音 session 字节数
    // --------------------------------------------------------

    uint32_t _sessionBytes;

    // --------------------------------------------------------
    // 当前 session 是否已经开始
    // --------------------------------------------------------

    bool _sessionActive;

    // --------------------------------------------------------
    // 当前 session 是否还没有发送 FIRST
    // --------------------------------------------------------

    bool _firstInSession;

    // --------------------------------------------------------
    // 最近一次发送时间
    // --------------------------------------------------------

    uint32_t _lastSendMs;

    // --------------------------------------------------------
    // 已经发送 RPTF，正在等待 PC 播放
    // --------------------------------------------------------

    bool _waitingForPlayback;

    // --------------------------------------------------------
    // 播放结束后的 cooldown 截止时间
    //
    // 0 表示当前没有 cooldown。
    // --------------------------------------------------------

    uint32_t _cooldownUntilMs;
};

#endif  // MIC_UPLOADER_H

