// ============================================================
// mic_adc.h - MAX9814 模拟 MEMS 麦克风 → ESP32-S3 ADC
// ============================================================
//
// MAX9814 输出模拟电压（静态 ~VDD/2），走 ESP32-S3 ADC1。
//
// 当前 PlatformIO 使用 Arduino-ESP32 / ESP-IDF
//
// 关键处理链：
//   1. ADC 约 50 kS/s，12-bit unsigned
//   2. 去直流偏置
//   3. 一阶低通
//   4. 50 kHz → 16 kHz 重采样
//   5. 软件增益
//   6. Ring Buffer
//
// 输出：
//   int16 mono PCM
//   16000 Hz
// ============================================================

#ifndef MIC_ADC_H
#define MIC_ADC_H

#include <Arduino.h>
#include <driver/adc.h>

// ============================================================
// 采样率
// ============================================================

#define MIC_ADC_SAMPLE_HZ     50000
#define MIC_TARGET_SAMPLE_HZ  16000

// ============================================================
// ADC 硬件参数
// ============================================================

#define MIC_ADC_UNIT          ADC_UNIT_1
#define MIC_ADC_WIDTH_BITS    12

#define MIC_ADC_MID_VALUE     2048
#define MIC_ADC_MAX_VALUE     4095

// ============================================================
// Ring Buffer
// ============================================================

// 原始采样缓冲预留
#define MIC_RAW_RING_SAMPLES  256

// 输出 PCM Ring Buffer
#define MIC_OUT_RING_SAMPLES  4096

// ============================================================
// 增益与滤波
// ============================================================

// << 1 = ×2
#define MIC_GAIN_SHIFT        1

// 一阶低通滤波器，Q13
//
// y = α*x + (8192-α)*y_prev
//
// 6554 / 8192 ≈ 0.8
#define MIC_LP_ALPHA_FIXED    6554

// ============================================================
// DC 偏置跟踪
// ============================================================

#define MIC_DC_TRACK_SHIFT    8

// ============================================================
// poll 时序
// ============================================================

// 每 2 ms 读取一批 ADC
#define MIC_POLL_US           2000


class MicAdc {
public:

    // --------------------------------------------------------
    // 构造函数
    // --------------------------------------------------------

    MicAdc();

    // --------------------------------------------------------
    // 初始化 ADC1
    //
    // ESP32-S3:
    //   GPIO1  → ADC1_CH0
    //   GPIO2  → ADC1_CH1
    //   ...
    //   GPIO10 → ADC1_CH9
    // --------------------------------------------------------

    void begin(int gpio);

    // --------------------------------------------------------
    // 主循环调用
    // --------------------------------------------------------

    void poll();

    // --------------------------------------------------------
    // 是否存在已经处理好的 PCM 样本
    // --------------------------------------------------------

    bool available() const;

    // --------------------------------------------------------
    // 批量读取 PCM
    // --------------------------------------------------------

    size_t read(int16_t *buf, size_t max_samples);

    // --------------------------------------------------------
    // 清空当前输出 Ring Buffer
    //
    // 注意：
    //   这里只丢弃已经缓存的 PCM。
    //   ADC 采集本身仍然可以继续。
    //
    // 用于：
    //   播放结束后丢弃喇叭声音残留数据。
    // --------------------------------------------------------

    void clear();

    // --------------------------------------------------------
    // 最近一次 ADC 去偏置后的值
    // --------------------------------------------------------

    int16_t lastRaw() const
    {
        return _lastRaw;
    }


private:

    // --------------------------------------------------------
    // 读取一批 ADC 原始数据
    // --------------------------------------------------------

    void readRawBatch();


private:

    // ADC channel
    adc1_channel_t _chan;

    // --------------------------------------------------------
    // 输出 Ring Buffer
    // --------------------------------------------------------

    int16_t _outRing[MIC_OUT_RING_SAMPLES];

    size_t _outHead;
    size_t _outTail;
    size_t _outCount;

    // --------------------------------------------------------
    // 重采样相位
    // --------------------------------------------------------

    uint32_t _phaseAcc;

    // --------------------------------------------------------
    // DC 偏置跟踪
    // --------------------------------------------------------

    int32_t _dcState;

    // --------------------------------------------------------
    // 低通滤波状态
    // --------------------------------------------------------

    int32_t _lpState;

    // --------------------------------------------------------
    // 最近一次原始去偏置值
    // --------------------------------------------------------

    int16_t _lastRaw;

    // --------------------------------------------------------
    // poll 时间
    // --------------------------------------------------------

    uint32_t _lastPollUs;

    // --------------------------------------------------------
    // ADC 是否已经初始化
    // --------------------------------------------------------

    bool _started;

    // --------------------------------------------------------
    // 当前 GPIO
    // --------------------------------------------------------

    int _gpio;
};

#endif  // MIC_ADC_H

